-- ============================================================
-- 1. Application roles
-- ============================================================
-- Both roles are created NOLOGIN so committed SQL never contains a
-- working credential. For Docker installs the init-db entrypoint
-- script ALTERs them to LOGIN with passwords from env vars. For
-- non-Docker installs an admin must run:
--   ALTER ROLE openestate_app WITH LOGIN PASSWORD '<secret>';
--   ALTER ROLE openestate_system WITH LOGIN PASSWORD '<secret>';

-- openestate_app: tenant-scoped queries. RLS is fully enforced.
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'openestate_app') THEN
    CREATE ROLE openestate_app WITH NOLOGIN NOINHERIT;
    COMMENT ON ROLE openestate_app IS
      'Tenant-scoped app role (RLS enforced). Enable LOGIN and set a password before use.';
  END IF;
END
$$;

-- openestate_system: cross-tenant system operations (company
-- creation, null-company audit rows, seed scripts). BYPASSRLS but
-- NOT a superuser — cannot create roles, databases, or run DDL.
-- The actual superuser (POSTGRES_USER) is reserved for migrations.
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'openestate_system') THEN
    CREATE ROLE openestate_system WITH NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE BYPASSRLS;
    COMMENT ON ROLE openestate_system IS
      'System role with BYPASSRLS for cross-tenant ops. Enable LOGIN and set a password before use.';
  END IF;
END
$$;

GRANT USAGE ON SCHEMA public TO openestate_app;
GRANT USAGE ON SCHEMA public TO openestate_system;

