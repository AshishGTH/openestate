-- ============================================================
-- 5. Row-Level Security
-- ============================================================
-- Tenant-scoped tables: company_id is matched against a
-- per-transaction session variable set by the application via
-- set_config('app.current_company_id', <uuid>, true).
--
-- FORCE ROW LEVEL SECURITY ensures policies apply even to the
-- table owner (the role that ran this migration). The DB-owner
-- superuser still bypasses RLS, which is correct — the system
-- Prisma client connects as the superuser to perform cross-
-- tenant operations.
--
-- The openestate_app role (non-superuser, NOBYPASSRLS) is used
-- by the tenant-scoped Prisma client and has RLS fully enforced.
--
-- current_setting(..., true) returns NULL when the variable is
-- not set, causing the UUID cast to fail or match nothing,
-- failing closed (zero rows returned).

-- Helper: tables with non-null company_id (standard policy)
DO $$
DECLARE
  tbl TEXT;
BEGIN
  FOR tbl IN
    SELECT unnest(ARRAY[
      'users', 'roles', 'custom_field_definitions', 'company_configs',
      'inquiry_sources', 'inquiry_types', 'follow_up_types',
      'communication_types', 'project_types', 'receipt_types',
      'registration_types', 'area_locations', 'document_types',
      'letter_templates', 'banks', 'charge_types', 'gst_rates',
      'tds_rules', 'interest_rules', 'transfer_fee_rules',
      'payment_plan_templates'
    ])
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format(
      'CREATE POLICY tenant_isolation_policy ON %I
         FOR ALL
         USING (company_id = current_setting(''app.current_company_id'', true)::uuid)
         WITH CHECK (company_id = current_setting(''app.current_company_id'', true)::uuid)',
      tbl
    );
  END LOOP;
END
$$;

-- audit_logs: company_id is nullable (system-level events have NULL).
-- USING: tenant queries see only rows matching their company_id;
--        NULL-company rows are invisible to the tenant client.
-- WITH CHECK: tenant client can only insert rows with a matching
--        company_id — never NULL. Null-company audit rows are
--        written exclusively by the system client (BYPASSRLS).
